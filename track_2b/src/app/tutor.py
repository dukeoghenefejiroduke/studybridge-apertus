"""Grounded StudyBridge tutor with optional Apertus generation."""

import os
import sys

from app.llm_client import ApertusClient


UNSUPPORTED_ANSWER = (
    "I could not find sufficiently grounded information in the "
    "ingested course materials to answer this question reliably."
)


class TutorEngine:
    def __init__(self, retrieval_engine, llm_client=None):
        self.retrieval_engine = retrieval_engine
        # External inference is opt-in so tests and local use do not
        # unexpectedly spend API credit.
        self.llm_client = llm_client

        self.is_testing = (
            bool(os.getenv("PYTEST_CURRENT_TEST"))
            or os.getenv("TESTING", "").lower() in {"1", "true", "yes"}
        )

    def _get_llm_client(self):
        if self.llm_client is not None:
            return self.llm_client

        force_test = os.getenv("STUDYBRIDGE_FORCE_LLM_TEST", "").strip().lower() in {"1", "true", "yes"}
        if self.is_testing and not force_test:
            return None

        base_url = os.getenv("LLM_BASE_URL", "").strip()
        enable_llm = (
            os.getenv("STUDYBRIDGE_ENABLE_LLM", "").strip().lower()
            in {"1", "true", "yes"}
        ) or force_test

        if enable_llm and base_url:
            return ApertusClient.from_env()

        return None

    def answer_question(self, query):
        if not isinstance(query, str) or not query.strip():
            return {
                "answer": UNSUPPORTED_ANSWER,
                "supported": False,
                "citations": [],
            }

        all_docs = self.retrieval_engine.ingestion_manager.get_all_documents()
        top_k = max(len(all_docs), 10) if all_docs else 10

        results = self.retrieval_engine.search(query, top_k=top_k)

        relevant_matches = [
            item for item in results
            if item.get("score", 0.0) >= 0.4
        ]

        if not relevant_matches:
            return {
                "answer": UNSUPPORTED_ANSWER,
                "supported": False,
                "citations": [],
            }

        citations = []
        seen_citations = set()

        for match in relevant_matches:
            key = (match.get("title"), match.get("source"))

            if key in seen_citations:
                continue

            seen_citations.add(key)
            citations.append({
                "title": match.get("title", "Untitled material"),
                "source": match.get("source", "N/A"),
                "timestamp": match.get("timestamp"),
            })

        # Limit the amount of context sent to the model.
        passages = relevant_matches[:5]

        client = self._get_llm_client()
        force_test = os.getenv("STUDYBRIDGE_FORCE_LLM_TEST", "").strip().lower() in {"1", "true", "yes"}
        if client is not None and (not self.is_testing or force_test):
            try:
                answer = client.generate(query, passages)
            except RuntimeError:
                # Do not silently substitute a local answer and claim
                # that it was generated by Apertus.
                return {
                    "answer": (
                        "The study materials contain potentially relevant "
                        "information, but the configured Apertus service "
                        "could not generate an answer. Please try again "
                        "when the model endpoint is available."
                    ),
                    "supported": True,
                    "citations": citations,
                    "generation_error": True,
                }

            return {
                "answer": answer,
                "supported": True,
                "citations": citations,
                "model": client.model,
                "generation_error": False,
            }

        # Preserve the original local behavior when no model is configured.
        synthesized_parts = []

        for match in relevant_matches:
            synthesized_parts.append(
                f"From {match.get('title', 'Material')} "
                f"({match.get('source', 'N/A')}): "
                f"{match.get('content', '')}"
            )

        answer_text = (
            "Based on the retrieved study materials:\n\n"
            + "\n\n".join(synthesized_parts)
        )

        return {
            "answer": answer_text,
            "supported": True,
            "citations": citations,
        }
